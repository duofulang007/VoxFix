import assert from 'node:assert/strict';
import {createMemeSearch} from './meme-search.mjs';
const requests=[],insertions=[];
let changes=0;
const panel=createMemeSearch({update:()=>changes++,insert:id=>insertions.push(id),request:(url,options)=>new Promise(resolve=>requests.push({url,options,resolve}))});
const tick=(ms=0)=>new Promise(resolve=>setTimeout(resolve,ms));
const reply=(request,data,ok=true)=>request.resolve({ok,json:async()=>data});
const id='0123456789abcdef01234567',second='1123456789abcdef01234567';
assert(panel.render().includes('meme-input-slot'));assert(!panel.render().includes('meme-categories'));
panel.activate(true);assert.equal(requests.length,0,'Empty search must not request recommendations');
panel.schedule('熊');panel.schedule('熊大');await tick(350);assert.equal(requests.length,1,'Typing is debounced');
assert(requests[0].url.includes(encodeURIComponent('熊大')));assert(!requests[0].url.includes('category='));
panel.schedule('猫');assert(requests[0].options.signal.aborted);
reply(requests[0],{items:[{id,title:'old'}]});await tick(350);
reply(requests[1],{items:[{id,title:'猫<img onerror="bad()">'}],tags:['不显示'],more:true});await tick();
assert(!panel.render().includes('old'));assert(!panel.render().includes('不显示'));assert(panel.render().includes('猫&lt;img'));
panel.action('meme-more');reply(requests[2],{items:[{id,title:'重复'},{id:second,title:'第二张'},{id:'javascript:bad',title:'bad'}],more:false});await tick();
assert.equal((panel.render().match(/data-action="meme-preview"/g)||[]).length,2);
panel.action('meme-preview',id);assert(panel.render().includes('role="dialog"'));panel.action('meme-insert');assert.deepEqual(insertions,[id]);
panel.schedule('下一项');panel.activate(false);await tick(350);assert.equal(requests.length,3,'Closing cancels a pending debounce');
panel.activate(true);reply(requests[3],{error:'网络失败'},false);await tick();assert(panel.render().includes('网络失败'));
panel.action('meme-retry');panel.search('');reply(requests[4],{items:[{id,title:'迟到'}]});await tick();assert(!panel.render().includes('迟到'));assert(!panel.render().includes('meme-preview'));
panel.reset();assert.equal(panel.query,'');assert(changes>0);
console.log('meme-search: inline search, debounce, stale responses, clearing, pagination, escaping, preview and retry passed');

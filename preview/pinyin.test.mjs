import assert from 'node:assert/strict';
import fs from 'node:fs';
import {setPinyinData,pinyinCandidates,nineCandidates,loadPinyin,setPhraseOptions,phraseSearch,associationCandidates,pinyinConsumed} from './pinyin.mjs';
setPinyinData(JSON.parse(fs.readFileSync(new URL('./pinyin-data.json',import.meta.url),'utf8')));
assert.ok(pinyinCandidates('NIHAO').includes('你好'));
assert.ok(pinyinCandidates('jianpan').includes('键盘'));
assert.ok(pinyinCandidates('tianqi').includes('天气'));
assert.ok(pinyinCandidates('zhongguo').includes('中国'));
assert.ok(pinyinCandidates('zg').includes('中国'));
assert.ok(pinyinCandidates('srf').includes('输入法'));
assert.ok(pinyinCandidates('zdy').includes('自定义'));
assert.ok(pinyinCandidates('ZG').includes('中国'));
assert.equal(pinyinCandidates('wzdl')[0],'我知道了');
assert.equal(pinyinCandidates('mtj')[0],'明天见');
assert.ok(pinyinCandidates('zhongg').includes('中国'));
assert.ok(pinyinCandidates('zhg').includes('中国'));
assert.ok(pinyinCandidates('ni').length>=9);
for(const input of ['b','c','f','n','q','x','sh','ni','shi']){
  const words=pinyinCandidates(input);
  assert(words.length&&words.every(word=>[...word].length===1),'One syllable must offer characters, not unfinished phrases: '+input);
}
assert.equal(pinyinCandidates('nininini')[0],'你你你你');
assert.match(pinyinCandidates('qqqqqq')[0],/^[\u3400-\u9fff]{6}$/,'Repeated initials must keep composing Chinese');
assert.equal(pinyinCandidates('nnnn')[0].length,4);
assert.equal(pinyinCandidates('ni',3).length,3);
assert.ok(pinyinCandidates("xi'an").includes('西安'));
assert.ok(!pinyinCandidates("xi'an").includes('先'),'Explicit boundary must reject a single xian syllable');
assert.ok(pinyinCandidates('nihaoma').some(word=>word.length>=3));
assert.deepEqual(pinyinCandidates('<script>'),[]);
assert.deepEqual(pinyinCandidates('constructor'),[]);
assert(associationCandidates('你').includes('好'));
assert(associationCandidates('你好').includes('吗'));
assert(associationCandidates('输入').includes('法'));
assert(pinyinCandidates('nihaoq').includes('你好'));
assert.equal(pinyinConsumed('nihaoq','你好'),5);
assert(pinyinCandidates('wojintianx').some(word=>word.startsWith('我今天')));
assert.equal(pinyinCandidates('woshurufa')[0],'我输入法');
assert.ok(nineCandidates('64426').includes('你好'));
assert.ok(nineCandidates("64'426").includes('你好'));
assert.equal(nineCandidates('64',9).length,9);
assert.deepEqual(nineCandidates('0'),[]);
globalThis.fetch=async path=>({json:async()=>JSON.parse(fs.readFileSync(new URL(path,import.meta.url),'utf8'))});
await loadPinyin();
setPhraseOptions(['我明天联系你'],['quotes','running']);
assert(pinyinCandidates('w').every(word=>[...word].length===1),'Phrase packs must not complete a single initial');
assert.equal(pinyinCandidates('wmtlxn')[0],'我明天联系你');
assert.equal(pinyinCandidates('bm')[0],'半马');
assert.ok(pinyinCandidates('sswnszpyxr').includes('世上无难事，只怕有心人。'));
assert.ok(phraseSearch('千里').some(text=>text.includes('始于足下')));
setPhraseOptions([],[]);
assert.deepEqual(phraseSearch('千里'),[]);
console.log('PASS: offline Chinese candidates, prefixes, phrase assembly and display limits');
